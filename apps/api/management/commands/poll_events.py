    # ==========================================================
    # THREAD EVENT PROCESSING
    # ==========================================================

    def process_event_in_thread(self, event_id):
        event = None
        try:
            event = Event.objects.filter(event_id=event_id).first()
            if event:
                self.process_event(event)
        except Exception as e:
            self.stdout.write(
                self.style.ERROR(f"Error in thread for Event {event_id}: {e}")
            )
            if event:
                try:
                    self.log_processing_failure(
                        event, self.get_camera_location(event), str(e)
                    )
                except Exception:
                    pass
        finally:
            connections.close_all()
    # ==========================================================
    # MAIN LOOP
    # ==========================================================

    def handle(self, *args, **options):

        self.stdout.write(
            self.style.SUCCESS(
                "Starting background event polling..."
            )
        )

        executor = ThreadPoolExecutor(
            max_workers=5
        )

        poll_interval = self.get_poll_interval()

        queued_events = set()

        self.stdout.write(
            self.style.SUCCESS(
                f"Alert polling configured: "
                f"interval={poll_interval}s, "
                f"noncritical_max_age="
                f"{self.get_noncritical_max_age_seconds()}s, "
                f"critical_max_age="
                f"{self.get_critical_max_age_seconds()}s"
            )
        )

        try:

            while True:

                try:

                    # ==================================================
                    # PASSWORD RESET
                    # ==================================================

                    for step in (
                        self.process_password_resets,
                        self.process_daily_summary_if_due,
                        self.process_event_count_summary_if_due,
                    ):
                        try:
                            step()
                        except Exception as step_error:
                            self.stdout.write(
                                self.style.ERROR(
                                    f"{step.__name__} failed: {step_error}"
                                )
                            )
                    # ==================================================
                    # RECENT EVENTS
                    # ==================================================

                    window_start = (
                        timezone.now()
                        - timedelta(minutes=15)
                    )

                    recent_events = (
                        Event.objects
                        .filter(
                            timestamp__gte=window_start
                        )
                        .order_by("event_id")
                    )

                    current_window_ids = set()

                    for event in recent_events:

                        current_window_ids.add(
                            event.event_id
                        )

                        if event.event_id in queued_events:
                            continue

                        already_processed = (
                            NotificationDeliveryLog.objects
                            .filter(
                                event_id=event.event_id
                            )
                            .exists()
                        )

                        if not already_processed:

                            (
                                should_send,
                                is_critical,
                                age_seconds,
                                max_age,
                            ) = self.should_send_event(event)

                            if not should_send:

                                level = (
                                    "CRITICAL"
                                    if is_critical
                                    else "NONCRITICAL"
                                )

                                self.stdout.write(
                                    self.style.WARNING(
                                        f"Skipping stale {level} "
                                        f"incident {event.event_id} "
                                        f"({event.event_type}) "
                                        f"age={age_seconds}s "
                                        f"max_age={max_age}s"
                                    )
                                )

                                camera_location = (
                                    self.get_camera_location(event)
                                )

                                self.log_stale_event_skip(
                                    event,
                                    camera_location,
                                    is_critical,
                                    age_seconds,
                                    max_age,
                                )

                                queued_events.add(
                                    event.event_id
                                )

                                continue

                            self.stdout.write(
                                f"Queuing alert for Event ID: "
                                f"{event.event_id}"
                            )

                            queued_events.add(
                                event.event_id
                            )

                            executor.submit(
                                self.process_event_in_thread,
                                event.event_id,
                            )

                    queued_events.intersection_update(
                        current_window_ids
                    )

                except Exception as e:

                    self.stdout.write(
                        self.style.ERROR(
                            f"Polling error: {str(e)}"
                        )
                    )

                time.sleep(
                    poll_interval
                )

        finally:

            executor.shutdown(
                wait=False
            )
            connections.close_all()

