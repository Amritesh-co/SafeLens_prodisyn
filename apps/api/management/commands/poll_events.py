    def get_camera_location(self, event):
        camera = getattr(event, "camera", None)

        if not camera:
            return "Unknown Location"

        location = getattr(camera, "location", None)

        if not location:
            return "Unknown Location"

        return getattr(
            location,
            "name",
            "Unknown Location"
        )

    def event_age_seconds(self, event):
        if not event.timestamp:
            return 0

        event_time = event.timestamp
        now = timezone.now()

        if timezone.is_naive(event_time) and timezone.is_aware(now):
            event_time = timezone.make_aware(
                event_time,
                timezone.get_current_timezone(),
            )

        elif timezone.is_aware(event_time) and timezone.is_naive(now):
            event_time = timezone.make_naive(
                event_time,
                timezone.get_current_timezone(),
            )

        return max(
            0,
            int(
                (now - event_time).total_seconds()
            ),
        )

    def should_send_event(self, event):
        age_seconds = self.event_age_seconds(event)

        critical = self.is_critical_event(
            getattr(event, "event_type", "")
        )

        if critical:
            max_age = self.get_critical_max_age_seconds()
        else:
            max_age = self.get_noncritical_max_age_seconds()

        if max_age and age_seconds > max_age:
            return (
                False,
                critical,
                age_seconds,
                max_age,
            )

        return (
            True,
            critical,
            age_seconds,
            max_age,
        )

