    def log_stale_event_skip(
        self,
        event,
        camera_location,
        is_critical,
        age_seconds,
        max_age,
    ):

        recipients = self.get_target_recipients(event)

        details = {
            "reason": "stale_event",
            "age_seconds": age_seconds,
            "max_age_seconds": max_age,
            "is_critical": is_critical,
            "camera_location": camera_location,
        }

        logged_any = False

        for recipient in recipients["email"]:

            self.log_delivery(
                event_id=event.event_id,
                channel="EMAIL",
                recipient=recipient,
                status="SKIPPED",
                provider="AWS_SES",
                error_message=(
                    "Skipped because event exceeded "
                    "freshness window"
                ),
                details=details,
            )

            logged_any = True

        for recipient in recipients["sms"]:

            self.log_delivery(
                event_id=event.event_id,
                channel="SMS",
                recipient=recipient,
                status="SKIPPED",
                provider="AWS_SNS",
                error_message=(
                    "Skipped because event exceeded "
                    "freshness window"
                ),
                details=details,
            )

            logged_any = True

        for recipient in recipients["whatsapp"]:

            self.log_delivery(
                event_id=event.event_id,
                channel="WHATSAPP",
                recipient=recipient,
                status="SKIPPED",
                provider="AWS_SOCIAL_MESSAGING",
                template_name=get_whatsapp_template_name(),
                error_message=(
                    "Skipped because event exceeded "
                    "freshness window"
                ),
                details=details,
            )

            logged_any = True

        if not logged_any:

            self.log_delivery(
                event_id=event.event_id,
                channel="WHATSAPP",
                recipient="NO_ELIGIBLE_RECIPIENTS",
                status="SKIPPED",
                provider="AWS_SOCIAL_MESSAGING",
                error_message=(
                    "Skipped because event exceeded "
                    "freshness window and no eligible "
                    "recipients were configured"
                ),
                details=details,
            )

