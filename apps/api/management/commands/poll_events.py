    def process_daily_summary_if_due(self):

        report_tz = pytz.timezone(self.REPORT_TIMEZONE)

        now = timezone.now()

        if timezone.is_naive(now):
            now = timezone.make_aware(
                now,
                timezone.get_current_timezone()
            )

        now_ist = timezone.localtime(now, report_tz)
        
        tracker = EmailAlertTracker.objects.filter(id=1).first()

        if not tracker:
            self.stdout.write(
                self.style.ERROR(
                    "EmailAlertTracker settings not found. "
                    "Daily Incident Summary will not run."
                )
            )
            return

        if not tracker.is_daily_summary_enabled:
            return

        summary_hour = tracker.daily_summary_time.hour
        summary_minute = tracker.daily_summary_time.minute

        if now_ist.hour != summary_hour:
            return

        if now_ist.minute != summary_minute:
            return

        run_key = (
            f"{now_ist.date().isoformat()}_"
            f"{summary_hour:02d}:{summary_minute:02d}"
        )

        if self.last_daily_summary_date == run_key:
            return

        self.stdout.write(
            self.style.SUCCESS(
                "\n=============================================="
            )
        )
        self.stdout.write(
            self.style.SUCCESS(
                "Starting Daily Incident Summary..."
            )
        )
        self.stdout.write(
            self.style.SUCCESS(
                "=============================================="
            )
        )

        try:
            self.generate_daily_incident_summary(
                schedule_version=tracker.daily_summary_schedule_version,
            )

            self.last_daily_summary_date = run_key

        except Exception as e:
            self.stdout.write(
                self.style.ERROR(
                    f"Daily summary error: {e}"
                )
            )   


