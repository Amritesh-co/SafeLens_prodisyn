    def get_target_recipients(self, event):
        email_recipients = []
        sms_recipients = []
        whatsapp_recipients = []
        teams_graph_recipients = []

        camera = getattr(event, "camera", None)
        tenant_config = getattr(camera, "tenant_config", None) if camera else None
        tenant = getattr(tenant_config, "tenant", None) if tenant_config else None
        location_id = camera.location_id if camera else None

        if (
            not camera
            or not tenant
            or not tenant_config.enabled
            or not camera.is_active
        ):
            return {
                "email": [], "sms": [], "whatsapp": [], "teams_graph": [],
            } 
        # Custom recipients have no tenant field, so they stay global (email only).
        email_recipients.extend(
            NotificationRecipient.objects
            .filter(is_active=True)
            .exclude(email__isnull=True)
            .exclude(email="")
            .values_list("email", flat=True)
        )

        # Users assigned to this event's location within this tenant
        assigned_user_ids = set(
            UserLocation.objects.filter(
                location__tenant=tenant,
                location__enabled=True,
                location__location_id=location_id,
            ).values_list("user_id", flat=True)
        )

        users = (
            User.objects
            .filter(
                is_active=True,
                profile__tenant=tenant,
                profile__status="Active",
            )
            .select_related("profile")
        )

        for user in users:
            profile = user.profile

            if profile.role in TENANT_WIDE_ROLES:
                should_notify = True
            elif profile.role in LOCATION_SCOPED_ROLES:
                should_notify = user.id in assigned_user_ids
            else:
                should_notify = False

            if not should_notify:
                continue

            if profile.alerts_email and user.email:
                email_recipients.append(user.email)

            if profile.phone_number:
                phone = re.sub(r"[^\d+]", "", profile.phone_number)
                if len(phone) == 10 and phone.isdigit():
                    phone = "+91" + phone
                elif not phone.startswith("+"):
                    phone = "+" + phone

                if profile.alerts_sms:
                    sms_recipients.append(phone)
                if profile.alerts_whatsapp:
                    whatsapp_recipients.append(phone)

            if profile.alerts_teams and user.email:
                teams_graph_recipients.append(
                    {"email": user.email, "profile": profile}
                )

        return {
            "email": list(set(email_recipients)),
            "sms": list(set(sms_recipients)),
            "whatsapp": list(set(whatsapp_recipients)),
            "teams_graph": teams_graph_recipients,
        }
