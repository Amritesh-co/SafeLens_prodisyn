    def process_event_count_summary_if_due(self):

        try:
            # ---------------------------------------------------------
            # REPORT TIMEZONE
            # ---------------------------------------------------------
            report_tz = pytz.timezone("Asia/Kolkata")

            now = timezone.now()

            if timezone.is_naive(now):
                now = report_tz.localize(now)
            else:
                now = timezone.localtime(now, report_tz)

            # ---------------------------------------------------------
            # TEST TRIGGER TIME: 17:35 IST
            # ---------------------------------------------------------

            if now.hour != 0 or now.minute != 5:

                return

            # ---------------------------------------------------------
            # PREVENT MULTIPLE EXECUTIONS ON THE SAME DAY
            # ---------------------------------------------------------
            run_date = now.date()

            if self.last_event_count_summary_date == run_date:
                return

            print(
                f"[Dashboard Report] Starting event count summary "
                f"generation at {now}"
            )

            # ---------------------------------------------------------
            # GENERATE REPORT
            # ---------------------------------------------------------
            result = calculate_event_count_summary()

            # ---------------------------------------------------------
            # MARK AS COMPLETED
            # ---------------------------------------------------------
            self.last_event_count_summary_date = run_date

            print(
                "[Dashboard Report] Event count summary "
                "generated successfully."
            )

            print(
                f"[Dashboard Report] Weekly data: "
                f"{result.get('weekly_data', {})}"
            )

            print(
                f"[Dashboard Report] Monthly data: "
                f"{result.get('monthly_data', {})}"
            )

        except Exception as e:
            print(
                f"[Dashboard Report] Failed to generate "
                f"event count summary: {e}"
            )

            traceback.print_exc()

    def get_poll_interval(self):
        try:
            return max(
                1.0,
                float(
                    os.environ.get(
                        "ALERT_POLL_INTERVAL_SECONDS",
                        "1",
                    )
                ),
            )
        except (TypeError, ValueError):
            return 1.0

    def get_noncritical_max_age_seconds(self):
        try:
            return max(
                0,
                int(
                    os.environ.get(
                        "ALERT_MAX_AGE_SECONDS",
                        "86400",
                    )
                ),
            )
        except (TypeError, ValueError):
            return 86400

    def get_critical_max_age_seconds(self):
        try:
            return max(
                0,
                int(
                    os.environ.get(
                        "ALERT_CRITICAL_MAX_AGE_SECONDS",
                        "86400",
                    )
                ),
            )
        except (TypeError, ValueError):
            return 86400

    def get_critical_event_markers(self):
        raw = os.environ.get(
            "ALERT_CRITICAL_EVENT_TYPES",
            (
                "FALL,INTRUSION,FALL_DETECTED,"
                "INTRUSION_DETECTED,UNATTENDED_OBJECT"
            ),
        )

        return [
            item.strip().upper()
            for item in raw.split(",")
            if item.strip()
        ]

    def is_critical_event(self, event_type):
        event_type = (event_type or "").upper()

        return any(
            marker in event_type
            for marker in self.get_critical_event_markers()
        )

