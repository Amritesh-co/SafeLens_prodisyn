    processed = models.BooleanField(default=False)
    processed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = 'auth_password_reset_event'
        ordering = ['-created_at']

    def is_valid(self):
        # Recovery token expires after 15 minutes to reduce vulnerability surfaces
        expiry_window = timezone.now() - timezone.timedelta(minutes=15)
        return not self.processed and self.created_at >= expiry_window


