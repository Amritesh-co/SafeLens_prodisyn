@receiver(post_save, sender=User)
def create_user_profile(sender, instance, created, **kwargs):
    if created:
        # Give them a default role and status so the frontend validations don't break
        # if a superuser blindly creates them via Django admin or shell.
        UserProfile.objects.get_or_create(
            user=instance,
            defaults={'role': DEFAULT_ROLE, 'status': 'Active'}
        )

