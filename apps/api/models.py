class EmailAlertTracker(models.Model):
    """
    Tracks the last event_id that was successfully processed.
    Contains global master switches for all notification channels.
    """
    last_event_id = models.IntegerField(default=0)
    last_checked = models.DateTimeField(auto_now=True)
    is_email_enabled = models.BooleanField(default=True, help_text="Global switch to enable/disable automated emails")
    is_sms_enabled = models.BooleanField(default=True, help_text="Global switch to enable/disable automated SMS")
    is_whatsapp_enabled = models.BooleanField(default=True, help_text="Global switch to enable/disable automated WhatsApp")
    is_teams_enabled = models.BooleanField(default=False, help_text="Global switch to enable/disable MS Teams channel notifications")
    is_teams_graph_enabled = models.BooleanField(default=False, help_text="Global switch to enable/disable Teams 1:1 Graph notifications")
    is_unattended_object_enabled = models.BooleanField(default=True, help_text="Global switch to enable/disable Unattended Object alerts")
    is_single_login_mode = models.BooleanField(default=False, help_text="Global switch to restrict the application to only one concurrent user globally")
    max_concurrent_sessions = models.IntegerField(default=1, help_text="Maximum number of active sessions allowed per user account")
    
    is_daily_summary_enabled = models.BooleanField(
        default=True,
        help_text="Global switch to enable/disable Daily Incident Summary emails"
    )

    daily_summary_time = models.TimeField(
        default=time(9, 0),
        help_text="Time when the Daily Incident Summary should be generated and emailed"
    )
    daily_summary_schedule_version = models.PositiveIntegerField(default=1)

    def save(self, *args, **kwargs):
        """Allow one resend when the configured daily-summary time changes."""
        if self.pk:
            previous_time = (
                type(self).objects
                .filter(pk=self.pk)
                .values_list("daily_summary_time", flat=True)
                .first()
            )

            if (
                previous_time is not None
                and previous_time != self.daily_summary_time
            ):
                self.daily_summary_schedule_version += 1

                if kwargs.get("update_fields") is not None:
                    kwargs["update_fields"] = set(
                        kwargs["update_fields"]
                    ) | {"daily_summary_schedule_version"}

        super().save(*args, **kwargs)
    class Meta:
        managed = True
        db_table = 'email_alert_tracker'
        verbose_name = 'Global Alert Setting'
        verbose_name_plural = 'Global Alert Settings'

    def __str__(self):
        return f"Global Settings (Last checked ID: {self.last_event_id})"

