class TenantUseCase(models.Model):
    """
    Defines which AI safety use cases are enabled for a tenant.

    This is configuration controlled by Django.
    It does not modify the existing AI-generated Event tables.
    """

    tenant = models.ForeignKey(
        Tenant,
        on_delete=models.CASCADE,
        related_name='use_cases'
    )

    code = models.CharField(
        max_length=100,
        help_text="Internal use-case code, e.g. FALL_DETECTION"
    )

    name = models.CharField(
        max_length=150,
        help_text="Display name shown in the frontend"
    )

    enabled = models.BooleanField(default=True)

    # Optional: controls whether this use case appears as a dashboard metric
    show_on_dashboard = models.BooleanField(default=True)

    # Optional: controls whether this use case appears in incident filters
    show_in_filters = models.BooleanField(default=True)

    match_config = models.JSONField(
        default=dict,
        blank=True,
        help_text=(
            "Rules used to match raw AI events to this use case."
        )
    )
    
    class Meta:
        managed = True
        db_table = 'tenant_use_cases'

        constraints = [
            models.UniqueConstraint(
                fields=['tenant', 'code'],
                name='unique_tenant_use_case'
            )
        ]

        ordering = ['name']

    def __str__(self):
        return f"{self.tenant.name} - {self.name}"

