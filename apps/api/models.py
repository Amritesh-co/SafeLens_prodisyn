class AssistantQueryLog(models.Model):
    """
    Managed model. Audit trail for every AI assistant question, including
    blocked/refused ones. Also used for per-user rate limiting.
    """

    STATUS_CHOICES = [
        ('ok', 'OK'),
        ('refused', 'Refused (off-topic)'),
        ('blocked', 'Blocked by input guardrail'),
        ('not_found', 'Data not found or not accessible'),
        ('ungrounded', 'Answer withheld (not grounded in data)'),
        ('leak', 'Answer withheld (leak check)'),
        ('rate_limited', 'Rate limited'),
        ('error', 'Error'),
    ]

    user = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, related_name='assistant_queries')
    tenant = models.ForeignKey('Tenant', on_delete=models.SET_NULL, null=True, blank=True)
    question = models.TextField()
    answer = models.TextField(blank=True, default='')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES)
    block_reason = models.CharField(max_length=255, blank=True, default='')
    tool_calls = models.JSONField(default=list, blank=True)
    model_name = models.CharField(max_length=100, blank=True, default='')
    latency_ms = models.IntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        managed = True
        db_table = 'assistant_query_log'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['user', 'created_at'], name='aql_user_created_idx'),
        ]

    def __str__(self):
        return f"{self.user_id} @ {self.created_at:%Y-%m-%d %H:%M} [{self.status}]"
